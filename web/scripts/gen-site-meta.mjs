// Writes `web/public/robots.txt` and `web/public/sitemap.xml` from PUBLIC_BASE_URL. Run via the
// `predev`/`prebuild` npm hooks, so both are current before the dev server or `vite build` starts.
//
// Both files must carry an absolute origin (a sitemap `<loc>` and the robots `Sitemap:` line are
// full URLs by spec), and that origin differs per environment. Generating them keeps the one source
// of truth — PUBLIC_BASE_URL, the same value the backend reads — instead of a committed guess.
// Output is git-ignored, like `web/public/tesseract/core/`.
//
// Only the evergreen public routes go in the sitemap: the `AuthGuard.Public` pages from
// `AppRouter.guardFor` that are not token- or session-specific. Per-word `/words/{id}` pages are the
// dynamic tier and are deliberately out of scope here.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const webRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const repoRoot = dirname(webRoot)
const publicDir = join(webRoot, 'public')

// Precedence: a real shell variable, then the repo-root `.env` (the file `reStart / envVars` and
// Vite both read), then application.conf's own default.
function baseUrl() {
  if (process.env.PUBLIC_BASE_URL) return process.env.PUBLIC_BASE_URL
  try {
    const env = readFileSync(join(repoRoot, '.env'), 'utf8')
    const line = env.split('\n').find((l) => /^\s*PUBLIC_BASE_URL\s*=/.test(l))
    if (line) return line.slice(line.indexOf('=') + 1).trim().replace(/^["']|["']$/g, '')
  } catch (e) {
    /* no .env — fall through */
  }
  return 'http://localhost:5173'
}

const origin = baseUrl().replace(/\/+$/, '')
const locales = ['en', 'hu']

// Path after the `/en` | `/hu` locale prefix. '' is the home route (`/en/`, kept with its slash, the
// form Waypoint builds).
const routes = ['', '/about', '/words', '/games/vocabulary-quiz', '/sign-up']

const url = (loc, path) => `${origin}/${loc}${path === '' ? '/' : path}`

const entries = routes
  .flatMap((path) =>
    locales.map((loc) => {
      const alts = locales
        .map((l) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${url(l, path)}"/>`)
        .concat(`    <xhtml:link rel="alternate" hreflang="x-default" href="${url('en', path)}"/>`)
        .join('\n')
      return `  <url>\n    <loc>${url(loc, path)}</loc>\n${alts}\n  </url>`
    }),
  )
  .join('\n')

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${entries}
</urlset>
`

const robots = `# Generated by web/scripts/gen-site-meta.mjs (predev/prebuild). Edit that script, not this file.
#
# GathEdge is a single-page app. Most routes need a sign-in and only return the app shell to a
# crawler. These rules keep bots off the API and off URLs that carry a one-time token or an admin
# screen.

User-agent: *
Allow: /

Disallow: /api/

Disallow: /admin/
Disallow: /en/admin/
Disallow: /hu/admin/

Disallow: /en/verify-email/
Disallow: /hu/verify-email/
Disallow: /en/reset-password/
Disallow: /hu/reset-password/
Disallow: /en/forgot-password
Disallow: /hu/forgot-password
Disallow: /en/check-inbox
Disallow: /hu/check-inbox

Sitemap: ${origin}/sitemap.xml
`

writeFileSync(join(publicDir, 'sitemap.xml'), sitemap)
writeFileSync(join(publicDir, 'robots.txt'), robots)
console.log(`gen-site-meta: wrote robots.txt + sitemap.xml for ${origin}`)
